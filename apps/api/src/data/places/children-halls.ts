type HallSeed = Pick<
  PlaceInput,
  'id' | 'name' | 'latitude' | 'longitude' | 'address' | 'municipalityCode'
> &
  Partial<
    Pick<
      PlaceInput,
      | 'shortDescription'
      | 'description'
      | 'businessHours'
      | 'closedDays'
      | 'accessInfo'
      | 'media'
    >
  >;

function hall(seed: HallSeed): PlaceInput {
  return {
    id: seed.id,
    name: seed.name,
    category: 'children-hall',
    latitude: seed.latitude,
    longitude: seed.longitude,
    address: seed.address,
    municipalityCode: seed.municipalityCode,
    suitableAgeMinMonths: 0,
    suitableAgeMaxMonths: 84,
    indoorOutdoor: 'indoor',
    priceLevel: 0,
    strollerFriendly: true,
    nursingRoom: true,
    diaperChanging: true,
    tags: ['group-play'],
    shortDescription: seed.shortDescription ?? `${seed.name}を利用できる児童館です。`,
    description: seed.description,
    businessHours: seed.businessHours ?? '10:00〜18:00',
    closedDays: seed.closedDays ?? '日曜・祝日・年末年始',
    accessInfo: seed.accessInfo,
    media: seed.media,
    sourceUrl: WARD_URL[seed.municipalityCode] ?? 'https://www.metro.tokyo.lg.jp',
    sourceCheckedAt: checkedAt,
    status: 'published',
  };
}

